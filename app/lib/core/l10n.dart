/// 文本国际化。轻量实现：不引 flutter_localizations 的 gen-l10n，
/// 用区域 + 语言的简单查表，MVP 阶段够用且没有生成步骤。
library;

import 'region.dart';

/// 当前语言。中文区默认 zh，海外默认 en。
/// 后续接入系统 locale 时只改这一处。
enum AppLang { zh, en }

class L {
  L._();

  static const String _raw = String.fromEnvironment('LANG');

  static AppLang get current {
    if (_raw == 'zh' || _raw == 'en') {
      return _raw == 'zh' ? AppLang.zh : AppLang.en;
    }
    return AppRegion.isCn ? AppLang.zh : AppLang.en;
  }

  static bool get isZh => current == AppLang.zh;

  /// 取文案。[key] 找不到时回落到 key 本身，便于开发期暴露漏翻。
  static String t(String key) {
    final table = isZh ? _zh : _en;
    return table[key] ?? _en[key] ?? key;
  }

  /// 两张表的键差。给测试用的 —— 加中文忘加英文是最常见的翻车方式，
  /// 而 [t] 的回落逻辑（zh 缺就去 en 找）会把它藏起来，运行期看不出来。
  static ({Set<String> onlyZh, Set<String> onlyEn}) tableDiff() {
    final zh = _zh.keys.toSet();
    final en = _en.keys.toSet();
    return (onlyZh: zh.difference(en), onlyEn: en.difference(zh));
  }

  /// 简单的占位符替换：'今天要做 {n} 件事' + {'n': '3'}
  static String tp(String key, Map<String, Object?> params) {
    var s = t(key);
    params.forEach((k, v) => s = s.replaceAll('{$k}', '${v ?? ''}'));
    return s;
  }

